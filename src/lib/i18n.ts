export function arabicTitle(name: string): string | undefined {
  return AR_TITLES[name.trim().toLowerCase()];
}

const EN_FROM_AR: Record<string, string> = Object.entries(AR_TITLES).reduce(
  (acc, [en, ar]) => {
    const key = ar.trim().toLowerCase();
    if (!(key in acc)) acc[key] = en.trim();
    return acc;
  },
  {} as Record<string, string>
);

/** Translate an Arabic search query into the English title when known. */
export function englishFromArabic(query: string): string | undefined {
  const q = query.trim().toLowerCase();
  return EN_FROM_AR[q] ?? EN_FROM_AR[q.replace(/\u0640/g, "")];
}

export function displayName(name: string, lang: UILang): string {
  if (lang === "ar") return arabicTitle(name) ?? name;
  return name;
}
