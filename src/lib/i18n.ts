export type DictKey = keyof (typeof DICT)["en"];

export function makeT(lang: UILang) {
  return (key: DictKey): string => {
    const d = DICT[lang] as Record<string, string>;
    return d[key] ?? DICT.en[key] ?? key;
  };
}

